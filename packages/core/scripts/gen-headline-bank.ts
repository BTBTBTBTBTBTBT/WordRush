// Generates the native copies of the Home headline bank from the TS source of truth
// (packages/core/src/home-headline-pool.ts → HEADLINE_BANK), so the three platforms read byte-equal words
// (like season-registry.json). Also rewrites §8 of docs/review/home-headlines/PROPOSAL.md.
//
//   apps/server/node_modules/.bin/tsx packages/core/scripts/gen-headline-bank.ts [--check]
//
// Outputs: apps/ios/Sources/Core/HomeHeadlineBank.swift, apps/android/core/src/main/kotlin/com/wordocious/core/HomeHeadlineBank.kt.
// The parity fixture (home-headline-pool-fixtures.json → `bank`) pins both copies to this bank in the native tests.

import fs from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HEADLINE_BANK } from '../src/home-headline-pool';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');

const HEADER = 'GENERATED by packages/core/scripts/gen-headline-bank.ts from packages/core/src/home-headline-pool.ts — do not edit.';
const entries = Object.entries(HEADLINE_BANK);
const total = entries.reduce((n, [, v]) => n + v.length, 0);

// Every line is plain ASCII + a few accented letters; escape only what a double-quoted literal needs in both languages.
const lit = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

function swift(): string {
  const out: string[] = [];
  out.push(`// ${HEADER}`);
  out.push('// The Home headline bank: `{name}` / `{next}` / `{last}` / `{left}` / `{played}` / `{total}` slots, tags as in the TS bank.');
  out.push('');
  out.push('public enum HomeHeadlineBank {');
  out.push('    /// The bank in TS order (tag → lines).');
  out.push('    public static let pools: [(tag: String, lines: [String])] = [');
  for (const [tag, lines] of entries) {
    out.push(`        (${lit(tag)}, [`);
    for (const l of lines) out.push(`            ${lit(l)},`);
    out.push('        ]),');
  }
  out.push('    ]');
  out.push('    private static let byTag: [String: [String]] = Dictionary(uniqueKeysWithValues: pools.map { ($0.tag, $0.lines) })');
  out.push('    /// The lines of one pool (empty when the tag is unknown).');
  out.push('    public static func pool(_ tag: String) -> [String] { byTag[tag] ?? [] }');
  out.push('}');
  return out.join('\n') + '\n';
}

function kotlin(): string {
  const out: string[] = [];
  out.push('package com.wordocious.core');
  out.push('');
  out.push(`// ${HEADER}`);
  out.push('// The Home headline bank: `{name}` / `{next}` / `{last}` / `{left}` / `{played}` / `{total}` slots, tags as in the TS bank.');
  out.push('');
  out.push('object HomeHeadlineBank {');
  out.push('    /** The bank in TS order (tag → lines). */');
  out.push('    val pools: List<Pair<String, List<String>>> = listOf(');
  for (const [tag, lines] of entries) {
    out.push(`        ${lit(tag)} to listOf(`);
    for (const l of lines) out.push(`            ${lit(l)},`);
    out.push('        ),');
  }
  out.push('    )');
  out.push('    private val byTag: Map<String, List<String>> = pools.toMap()');
  out.push('    /** The lines of one pool (empty when the tag is unknown). */');
  out.push('    fun pool(tag: String): List<String> = byTag[tag] ?: emptyList()');
  out.push('}');
  return out.join('\n') + '\n';
}

function proposalSection(): string {
  const out: string[] = [];
  out.push('## 8. The copy bank (generated from `home-headline-pool.ts`)');
  out.push('');
  out.push('Tags: `time/<bucket>`, `weekday/<0=Sun..6>`, `holiday/<key>`, `pack/<pack>`, `<context>` and `<context>/<pack>` flavors, `surprise`, `unlimited`. Slots as in §3.4.');
  out.push('');
  out.push(`Total: ${total} lines in ${entries.length} pools (plus the ~70 existing streak lines in streak-headline.ts, unchanged).`);
  for (const [tag, lines] of entries) {
    out.push('');
    out.push(`#### ${tag} (${lines.length})`);
    out.push('');
    for (const l of lines) out.push(`- \`${l}\``);
  }
  return out.join('\n') + '\n';
}

const proposalPath = join(repo, 'docs', 'review', 'home-headlines', 'PROPOSAL.md');
function proposal(): string {
  const cur = fs.readFileSync(proposalPath, 'utf8');
  const at = cur.indexOf('## 8. The copy bank');
  return (at >= 0 ? cur.slice(0, at) : cur.trimEnd() + '\n\n') + proposalSection();
}

const FILES: Array<[string, () => string]> = [
  [join(repo, 'apps', 'ios', 'Sources', 'Core', 'HomeHeadlineBank.swift'), swift],
  [join(repo, 'apps', 'android', 'core', 'src', 'main', 'kotlin', 'com', 'wordocious', 'core', 'HomeHeadlineBank.kt'), kotlin],
  [proposalPath, proposal],
];

const checkOnly = process.argv.includes('--check');
let drift = false;
for (const [target, render] of FILES) {
  const rendered = render();
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== rendered) {
    drift = true;
    if (checkOnly) console.error(`STALE: ${target} — regenerate with gen-headline-bank.ts`);
    else { fs.writeFileSync(target, rendered); console.log(`wrote ${target}`); }
  }
}
if (checkOnly) { console.log(drift ? 'headline bank STALE' : 'headline bank up to date'); process.exit(drift ? 1 : 0); }
if (!drift) console.log('headline bank already up to date');
