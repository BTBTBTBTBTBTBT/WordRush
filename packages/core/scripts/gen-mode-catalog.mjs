#!/usr/bin/env node
// Codegen: packages/core/modes.json → native mode-catalog files + SQL era functions.
// Run: `pnpm gen:modes` (from repo root). Web imports the generated TS; this
// script emits the Swift + Kotlin equivalents so name/accent/glyph/order/dbKey/
// group/sweep live in ONE place, plus the Postgres functions that make the sweep
// RPCs era-aware. Icons stay platform-native (keyed by id/dbKey).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const catalog = JSON.parse(readFileSync(join(here, '..', 'modes.json'), 'utf8'));
const modes = catalog.modes;
const eras = catalog.sweepEras;
const moreCategories = catalog.moreCategories;

const swiftOpt = (v) => (v == null ? 'nil' : `"${v}"`);
const ktOpt = (v) => (v == null ? 'null' : `"${v}"`);
const swiftList = (xs) => `[${xs.map((x) => `"${x}"`).join(', ')}]`;
const ktList = (xs) => `listOf(${xs.map((x) => `"${x}"`).join(', ')})`;

// ── Swift ────────────────────────────────────────────────────────────────────
const swift = `// GENERATED by packages/core/scripts/gen-mode-catalog.mjs from modes.json — DO NOT EDIT.
// Run \`pnpm gen:modes\` to regenerate. Edit packages/core/modes.json instead.
import SwiftUI

struct GenMode: Identifiable {
    let id: String
    let dbKey: String?
    let title: String
    let shortTitle: String
    let shareLabel: String
    let desc: String
    let accentHex: String
    let glyph: String?
    let romanNumeral: String?
    let dailyEligible: Bool
    /// "core" = home grid tile, "more" = More Games sheet.
    let group: String
    /// Counts toward the Daily Sweep / Flawless.
    let sweep: Bool
    /// "word" = shared reducer, "custom" = the mode's own view.
    let engine: String
    /// What guess_count means: guesses, mistakes, checks, overPar, misses, rank.
    let guessSemantics: String
    /// The perfect guess_count; display shows guess_count − guessBase.
    let guessBase: Int
    /// Reading order of the home grid (2 × 5). The array order stays the sweep/canonical order.
    let homeSlot: Int
    /// Rendered as a full-width tile UNDER the grid (More Games band, VS Battle live tile), not a grid cell.
    let homeWide: Bool
    /// Compiled in and visible (remote flag may still hide it).
    let enabled: Bool
    let flagKey: String?
    /// More Games sheet section key.
    let category: String?
    let guideSlug: String?
    var accent: Color { Color(hexString: accentHex) ?? .purple }
}

struct GenSweepEra { let since: String; let modes: [String] }
struct GenCategory { let key: String; let title: String }

enum ModeGen {
    static let all: [GenMode] = [
${modes.map((m) => `        GenMode(id: "${m.id}", dbKey: ${swiftOpt(m.dbKey)}, title: "${m.title}", shortTitle: "${m.shortTitle}", shareLabel: "${m.shareLabel}", desc: "${m.desc}", accentHex: "${m.accentHex}", glyph: ${swiftOpt(m.glyph)}, romanNumeral: ${swiftOpt(m.romanNumeral)}, dailyEligible: ${m.dailyEligible}, group: "${m.group}", sweep: ${m.sweep}, engine: "${m.engine}", guessSemantics: "${m.guessSemantics}", guessBase: ${m.guessBase}, homeSlot: ${m.homeSlot}, homeWide: ${m.homeWide}, enabled: ${m.enabled}, flagKey: ${swiftOpt(m.flagKey)}, category: ${swiftOpt(m.category)}, guideSlug: ${swiftOpt(m.guideSlug)})`).join(',\n')},
    ]
    static func byDbKey(_ k: String) -> GenMode? { all.first { $0.dbKey == k } }
    static func byId(_ i: String) -> GenMode? { all.first { $0.id == i } }
    /// Enabled modes only — what this build shows anywhere.
    static var enabled: [GenMode] { all.filter { $0.enabled } }
    /// Daily modes (VS excluded), canonical order — every daily-recordable mode this build knows.
    static var daily: [GenMode] { enabled.filter { $0.dailyEligible && $0.dbKey != nil } }
    /// The current required Daily Sweep set, canonical order.
    static var sweep: [GenMode] { daily.filter { $0.sweep } }
    /// Home grid tiles.
    static var core: [GenMode] { enabled.filter { $0.group == "core" }.sorted { $0.homeSlot < $1.homeSlot } }
    /// More Games sheet entries.
    static var more: [GenMode] { enabled.filter { $0.group == "more" } }
    static let moreCategories: [GenCategory] = [
${moreCategories.map((c) => `        GenCategory(key: "${c.key}", title: "${c.title}")`).join(',\n')},
    ]
    /// Sweep eras, newest first. Which dbKeys formed the required sweep on a given local day.
    static let sweepEras: [GenSweepEra] = [
${eras.map((e) => `        GenSweepEra(since: "${e.since}", modes: ${swiftList(e.modes)})`).join(',\n')},
    ]
    static func sweepModes(for day: String) -> [String] {
        for era in sweepEras where day >= era.since { return era.modes }
        return sweepEras.last?.modes ?? []
    }
    static func requiredSweepCount(for day: String) -> Int { sweepModes(for: day).count }
}
`;

// ── Kotlin ───────────────────────────────────────────────────────────────────
