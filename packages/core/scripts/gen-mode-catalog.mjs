// ── Web (TS) ─────────────────────────────────────────────────────────────────
const ts = `// GENERATED by packages/core/scripts/gen-mode-catalog.mjs from modes.json — DO NOT EDIT.
// Run \`pnpm gen:modes\` to regenerate. Edit packages/core/modes.json instead.

export type ModeGroup = 'core' | 'more';
export type ModeEngine = 'word' | 'custom';
export type GuessSemantics = 'guesses' | 'mistakes' | 'checks' | 'overPar' | 'misses' | 'rank';

export interface ModeMeta {
  id: string;
  dbKey: string | null;
  title: string;
  shortTitle: string;
  shareLabel: string;
  desc: string;
  accentHex: string;
  glyph: string | null;
  romanNumeral: string | null;
  dailyEligible: boolean;
  /** Home grid tile (core) or More Games sheet (more). */
  group: ModeGroup;
  /** Counts toward the Daily Sweep / Flawless. */
  sweep: boolean;
  /** Shared word reducer, or the mode's own view. */
  engine: ModeEngine;
  /** What guess_count means, for labels. */
  guessSemantics: GuessSemantics;
  /** The perfect guess_count; display shows guess_count − guessBase. */
  guessBase: number;
  /** Reading order of the home grid (2 × 5); the array order stays the sweep/canonical order. */
  homeSlot: number;
  /** Rendered as a full-width tile UNDER the grid (More Games band, VS Battle live tile), not a grid cell. */
  homeWide: boolean;
  /** Compiled in and visible (a remote flag may still hide it). */
  enabled: boolean;
  flagKey: string | null;
  /** More Games sheet section key. */
  category: string | null;
  guideSlug: string | null;
}

export interface SweepEra { since: string; modes: string[] }
export interface MoreCategory { key: string; title: string }

export const MODES: ModeMeta[] = ${JSON.stringify(modes, null, 2)};

export const MODE_BY_ID: Record<string, ModeMeta> = Object.fromEntries(MODES.map((m) => [m.id, m]));
export const MODE_BY_DBKEY: Record<string, ModeMeta> = Object.fromEntries(
  MODES.filter((m) => m.dbKey).map((m) => [m.dbKey as string, m]),
);
/** Enabled modes only — what this build shows anywhere. */
export const ENABLED_MODES: ModeMeta[] = MODES.filter((m) => m.enabled);
/** Daily modes (VS excluded), canonical order — every daily-recordable mode this build knows. */
export const DAILY_MODES: ModeMeta[] = ENABLED_MODES.filter((m) => m.dailyEligible && m.dbKey);
/** The current required Daily Sweep set, canonical order. */
export const SWEEP_MODES: ModeMeta[] = DAILY_MODES.filter((m) => m.sweep);
/** Home grid tiles. */
export const CORE_MODES: ModeMeta[] = ENABLED_MODES.filter((m) => m.group === 'core').sort((a, b) => a.homeSlot - b.homeSlot);
/** More Games sheet entries. */
export const MORE_GAME_MODES: ModeMeta[] = ENABLED_MODES.filter((m) => m.group === 'more');
export const MORE_CATEGORIES: MoreCategory[] = ${JSON.stringify(moreCategories)};

/** Sweep eras, newest first: which dbKeys formed the required sweep on a given local day. Append-only. */
export const SWEEP_ERAS: SweepEra[] = ${JSON.stringify(eras)};

/** The dbKeys a player had to record on \`day\` (local YYYY-MM-DD) for a sweep. ISO string compare is safe. */
export function sweepModesFor(day: string): string[] {
  for (const era of SWEEP_ERAS) if (day >= era.since) return era.modes;
  return SWEEP_ERAS[SWEEP_ERAS.length - 1].modes;
}
export function requiredSweepCount(day: string): number { return sweepModesFor(day).length; }
`;

// ── SQL (era functions) ──────────────────────────────────────────────────────
const sqlCase = eras.map((e) => `    when p_day >= '${e.since}' then array[${e.modes.map((m) => `'${m}'`).join(', ')}]::text[]`).join('\n');
const sql = `-- GENERATED by packages/core/scripts/gen-mode-catalog.mjs from modes.json — DO NOT EDIT.
-- Run \`pnpm gen:modes\` to regenerate, then paste into the Supabase SQL editor.
-- The sweep RPCs call these instead of hard-coding the mode list and the number 9,
-- so a change of era (Stage 9) is one regenerated function, never an RPC edit.
-- Idempotent: create or replace only. p_day is the local day, 'YYYY-MM-DD'.

create or replace function public.sweep_modes_for_day(p_day text)
returns text[]
language sql immutable parallel safe
set search_path = public
as $$
  select case
${sqlCase}
    else array[${eras[eras.length - 1].modes.map((m) => `'${m}'`).join(', ')}]::text[]
  end
$$;

create or replace function public.sweep_required_count(p_day text)
returns int
language sql immutable parallel safe
set search_path = public
as $$
  select coalesce(array_length(public.sweep_modes_for_day(p_day), 1), 0)
$$;

-- Probes (expected values as of this generation):
${eras.map((e) => `--   select sweep_required_count('${e.since === '0000-00-00' ? '2026-01-01' : e.since}');  -- ${e.modes.length}`).join('\n')}
`;

/** The generated outputs, exported so the staleness guard
 *  (apps/web/scripts/modes-codegen.test.ts) can compare rendered-vs-committed
 *  without writing anything. */
export const OUTPUTS = [
  { path: join(root, 'apps/ios/Wordocious/Sources/ModeCatalog.generated.swift'), content: swift },
  { path: join(root, 'apps/android/app/src/main/kotlin/com/wordocious/app/ModeCatalog.generated.kt'), content: kotlin },
  { path: join(root, 'apps/web/lib/modes.generated.ts'), content: ts },
  { path: join(root, 'supabase/generated/sweep_eras.generated.sql'), content: sql },
];
export const CATALOG = catalog;

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain && process.argv.includes('--check')) {
  // Staleness check: modes.json edited but gen:modes not re-run.
  let stale = 0;
  for (const { path, content } of OUTPUTS) {
    if (readFileSync(path, 'utf8') !== content) { console.error(`STALE: ${path} — run pnpm gen:modes`); stale++; }
  }
  process.exit(stale ? 1 : 0);
} else if (isMain) {
  for (const { path, content } of OUTPUTS) writeFileSync(path, content);
  console.log(`gen:modes — wrote ${modes.length} modes →`);
  for (const { path } of OUTPUTS) console.log(`  ${path}`);
}
