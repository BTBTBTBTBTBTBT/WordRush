#!/usr/bin/env node
// Social Studio: turn JP's 45-day plan (lib/admin/jp45-posts.json, the source of truth) into draft posts.
//
//   node apps/web/scripts/jp45-posts.mjs
//
// Writes docs/sql/20261014-jp45-posts.sql: social_posts, social_post_targets and marketing_links rows,
// idempotent. Re-running updates a post only while it is still an untouched draft (version 1, no review
// yet); a target only while it is still 'pending'. Media is never touched here (see social-attach.mjs).
// Times in the JSON are America/Chicago wall-clock; the SQL converts with `at time zone`-style literals.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(WEB, 'lib/admin/jp45-posts.json');
const SQL = join(WEB, '../../docs/sql/20261014-jp45-posts.sql');
const { posts } = JSON.parse(readFileSync(SRC, 'utf8'));

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
/** Same rule as targetSlug() in lib/admin/studio.ts: p-<last 8 hex of the post id>-<platform>. */
const slugFor = (id, platform) => `p-${id.replace(/-/g, '').slice(-8).toLowerCase()}-${platform}`;

const lines = [
  '-- APPLIED: 2026-10-14 ~9:30 PM CT to production (backup 20261015T022311Z). Read back: 122 new posts (93 plan slots + 29 video drafts), 227 targets, 227 tracked links; 40 posts paused (29 videos + 11 waiting on a fact); re-run verified idempotent.',
  "-- Social Studio: JP's 45-day plan as drafts (generated by apps/web/scripts/jp45-posts.mjs from",
  '-- apps/web/lib/admin/jp45-posts.json; idempotent). Every post is a draft that needs BMT + JP approval.',
  '-- Re-running only refreshes untouched drafts (version 1, no review) and still-pending targets.',
  'begin;',
];

for (const p of posts) {
  const at = `${p.date} ${p.time}:00 America/Chicago`;
  const tags = `{${p.hashtags.join(',')}}`;
  lines.push(
    `insert into public.social_posts (id, title, kind, scheduled_at, hashtags, media, link_target, paused, created_by)
values (${q(p.id)}, ${q(p.title)}, ${q(p.kind)}, ${q(at)}::timestamptz, ${q(tags)}::text[], '[]'::jsonb, ${q(p.link_target)}, ${p.paused ? 'true' : 'false'}, 'claude')
on conflict (id) do update set title = excluded.title, kind = excluded.kind, scheduled_at = excluded.scheduled_at,
  hashtags = excluded.hashtags, link_target = excluded.link_target, paused = excluded.paused, updated_at = now()
where public.social_posts.status = 'draft' and public.social_posts.version = 1
  and not exists (select 1 from public.social_reviews r where r.post_id = public.social_posts.id);`,
  );
  for (const t of p.targets) {
    const slug = slugFor(p.id, t.platform);
    lines.push(
      `insert into public.marketing_links (slug, target, channel) values (${q(slug)}, ${q(p.link_target)}, ${q(t.platform)}) on conflict (slug) do nothing;`,
      `insert into public.social_post_targets (post_id, platform, caption, link_slug) values (${q(p.id)}, ${q(t.platform)}, ${q(t.caption)}, ${q(slug)})
on conflict (post_id, platform) do update set caption = excluded.caption, link_slug = excluded.link_slug, updated_at = now()
where public.social_post_targets.status = 'pending'
  and exists (select 1 from public.social_posts sp where sp.id = public.social_post_targets.post_id and sp.version = 1 and sp.status = 'draft');`,
    );
  }
}
lines.push('commit;', '');
writeFileSync(SQL, lines.join('\n'));
const targets = posts.reduce((n, p) => n + p.targets.length, 0);
console.log(`wrote ${posts.length} posts / ${targets} targets to ${SQL}`);
