/**
 * Cross-platform parity guard for the Friends overhaul (2026-10-01): the pocket
 * game rules, the card lines and headlines, presence, friend streaks and the
 * Friends banner words must match packages/core/src/friendly-games.ts exactly
 * (friendly-games-fixtures.json, generated by gen-parity-fixtures.ts — the
 * scripts there: coin flips 0.1, 0.1, 0.1, 0.7, 0.3; Pass answer RISKS; Ghost
 * and Word Chain check words against the fixture's own `words` list; card
 * lines with minutesAgo 4 for side a vs "Doug" and 75 for side b vs "BT").
 * Every step also pins the error a rejected move returns.
 */
class FriendlyGamesFixtureTest {
    private val root: JsonObject by lazy {
        Json.parseToJsonElement(javaClass.classLoader!!.getResource("fixtures/friendly-games-fixtures.json")!!.readText()).jsonObject
    }

    private fun JsonElement?.strOrNull(): String? = (this as? JsonPrimitive)?.takeIf { this !is JsonNull }?.contentOrNull

    @Test
    fun games_replay_every_step() {
        val games = root["games"]!!.jsonArray
        assertEquals(6, games.size)
        // Ghost and Word Chain rebuild isWord / hasPrefix from the fixture's word list.
        val words = root["words"]!!.jsonArray.map { it.jsonPrimitive.content }
        val isWord: (String) -> Boolean = { it in words }
        val hasPrefix: (String) -> Boolean = { f -> words.any { it.startsWith(f) } }
        var steps = 0
        for (g in games) {
            val kind = FriendlyKind.from(g.jsonObject["kind"].strOrNull())!!
            val solution = if (kind == FriendlyKind.PASS) "RISKS" else null
            val flips = ArrayDeque(if (kind == FriendlyKind.COIN) listOf(0.1, 0.1, 0.1, 0.7, 0.3) else emptyList())
            val wordGame = kind == FriendlyKind.GHOST || kind == FriendlyKind.CHAIN
            val ctx = MoveContext(
                random = { flips.removeFirstOrNull() ?: 0.1 },
                solution = solution,
                isWord = if (wordGame) isWord else null,
                hasPrefix = if (wordGame) hasPrefix else null,
            )
            var s = newFriendlyState(kind)
            for (stepEl in g.jsonObject["steps"]!!.jsonArray) {
                val step = stepEl.jsonObject
                val by = Side.from(step["by"].strOrNull())!!
                val move = FriendlyMove.fromJson(step["move"])!!
                // The move's wire shape round-trips (what the app POSTs).
                assertEquals("move json $step", step["move"], move.toJson())
                val r = applyFriendlyMove(s, by, move, ctx)
                assertEquals("ok $step", step["ok"]!!.jsonPrimitive.boolean, r is MoveResult.Ok)
                assertEquals("error $step", step["error"].strOrNull(), (r as? MoveResult.Err)?.error)
                if (r is MoveResult.Ok) s = r.state
                val expected = decodeFriendlyState(step["state"])
                assertEquals("state $step", expected, s)
                assertEquals("turn $step", step["turn"].strOrNull(), whoseTurn(s)?.raw)
                assertEquals("winner $step", step["winner"].strOrNull(), friendlyWinner(s)?.raw)
                assertEquals("headlineA $step", step["headlineA"].strOrNull(), friendlyHeadline(s, Side.A))
                assertEquals("headlineB $step", step["headlineB"].strOrNull(), friendlyHeadline(s, Side.B))
                assertEquals("cardA $step", step["cardA"].strOrNull(), friendlyCardLine(s, Side.A, "Doug", 4))
                assertEquals("cardB $step", step["cardB"].strOrNull(), friendlyCardLine(s, Side.B, "BT", 75))
                steps++
            }
        }
        assertEquals(44, steps)
    }

    @Test
    fun boards_find_the_line() {
        val boards = root["boards"]!!.jsonArray
        assertTrue(boards.isNotEmpty())
        for (c in boards) {
            val o = c.jsonObject
            val board = o["board"]!!.jsonArray.map { Side.from(it.strOrNull()) }
            val got = tttLine(board)
            val line = o["line"]
            if (line == null || line is JsonNull) {
                assertNull("line $o", got)
            } else {
                assertNotNull("line $o", got)
                assertEquals("side $o", line.jsonObject["side"].strOrNull(), got!!.side.raw)
                assertEquals("cells $o", line.jsonObject["cells"]!!.jsonArray.map { it.jsonPrimitive.int }, got.cells)
            }
        }
    }

    @Test
    fun presence_matches() {
        val cases = root["presence"]!!.jsonArray
        assertEquals(9, cases.size)
        for (c in cases) {
            val o = c.jsonObject
            val last = (o["lastSeenMs"] as? JsonPrimitive)?.longOrNull
            val now = o["nowMs"]!!.jsonPrimitive.long
            val activity = o["activity"].strOrNull()
            assertEquals("online $o", o["online"]!!.jsonPrimitive.boolean, isOnline(last, now))
            assertEquals("line $o", o["line"].strOrNull(), presenceLine(last, activity, now))
        }
    }

    @Test
    fun friend_streaks_match() {
        val cases = root["streaks"]!!.jsonArray
        assertEquals(5, cases.size)
        for (c in cases) {
            val o = c.jsonObject
            val mine = o["mine"]!!.jsonArray.map { it.jsonPrimitive.content }
            val theirs = o["theirs"]!!.jsonArray.map { it.jsonPrimitive.content }
            assertEquals("streak $o", o["streak"]!!.jsonPrimitive.int, friendStreak(mine, theirs, o["today"]!!.jsonPrimitive.content))
