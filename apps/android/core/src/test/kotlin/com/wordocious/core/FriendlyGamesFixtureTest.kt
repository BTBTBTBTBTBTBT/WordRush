            assertEquals("clock $o", o["clock"].strOrNull(), friendsBannerClockLine(input, "04:12:08"))
        }
    }

    @Test
    fun hidden_picks_and_constants() {
        // The server sends the friend's open RPS pick as "hidden".
        val view = decodeFriendlyState(Json.parseToJsonElement("""{"kind":"rps","picks":{"a":"hidden"},"rounds":[],"score":{"a":0,"b":0}}"""))
        assertTrue(view is RpsState)
        assertEquals(RpsPick.HIDDEN, (view as RpsState).picks[Side.A])
        assertEquals(FriendlyTurn.B, whoseTurn(view))
        val s = (applyFriendlyMove(newFriendlyState(FriendlyKind.RPS), Side.A, FriendlyMove.Rps(RpsPick.PAPER)) as MoveResult.Ok).state
        assertEquals(RpsPick.HIDDEN, (friendlyStateFor(s, Side.B) as RpsState).picks[Side.A])
        assertEquals(RpsPick.PAPER, (friendlyStateFor(s, Side.A) as RpsState).picks[Side.A])
        assertTrue(applyFriendlyMove(s, Side.A, FriendlyMove.Rps(RpsPick.ROCK)) is MoveResult.Err)
        assertEquals(listOf("Bragging rights", "Loser picks tonight's VS mode", "Winner goes first next time"), COIN_STAKES)
        assertEquals("Bragging rights", (newFriendlyState(FriendlyKind.COIN, "anything") as CoinState).stake)
        assertEquals("Tic-Tac-Tile", FriendlyKind.TTT.title)
        assertEquals("Pass the Puzzle", FRIENDLY_TITLES[FriendlyKind.PASS])
        // Pass the Puzzle rejects a non-word and an invalid word with the TS errors.
        val pass = newFriendlyState(FriendlyKind.PASS)
        assertEquals(MoveResult.Err("Five letters, please"), applyFriendlyMove(pass, Side.A, FriendlyMove.Pass("abc"), MoveContext(solution = "RISKS")))
        assertEquals(MoveResult.Err("Not in the word list"), applyFriendlyMove(pass, Side.A, FriendlyMove.Pass("ZZZZZ"), MoveContext(solution = "RISKS", isValidWord = { it != "ZZZZZ" })))
        // Ghost and Word Chain: titles, order, and the inline errors.
        assertEquals(listOf("rps", "ttt", "coin", "pass", "ghost", "chain"), FRIENDLY_KINDS.map { it.raw })
        assertEquals("Word Chain", FriendlyKind.CHAIN.title)
        val ghost = newFriendlyState(FriendlyKind.GHOST)
        assertEquals(MoveResult.Err("One letter, please"), applyFriendlyMove(ghost, Side.A, FriendlyMove.Ghost("ab")))
        assertEquals(MoveResult.Err("Try another letter"), applyFriendlyMove(ghost, Side.A, FriendlyMove.Ghost("x"), MoveContext(blocked = { it == "X" })))
        val chain = newFriendlyState(FriendlyKind.CHAIN)
        assertEquals(MoveResult.Err("5 to 7 letters, please"), applyFriendlyMove(chain, Side.A, FriendlyMove.Chain("abc")))
        assertEquals(MoveResult.Err("5 to 7 letters, please"), applyFriendlyMove(chain, Side.A, FriendlyMove.Chain("ABCDEFGH")))
        assertEquals(MoveResult.Err("Not in the word list"), applyFriendlyMove(chain, Side.A, FriendlyMove.Chain("zzzzz"), MoveContext(isWord = { false })))
        val one = (applyFriendlyMove(chain, Side.A, FriendlyMove.Chain("crane")) as MoveResult.Ok).state
        val two = (applyFriendlyMove(one, Side.B, FriendlyMove.Chain("eerie")) as MoveResult.Ok).state
        assertEquals(MoveResult.Err("Already played"), applyFriendlyMove(two, Side.A, FriendlyMove.Chain("EERIE")))
        // Ghost stops after five rounds: the leader wins, level is a draw.
        val capped = GhostState(rounds = List(5) { GhostRound("Q", Side.B, GhostReason.DEAD) }, score = FriendlyScore(1, 1))
        assertEquals(FriendlyWinner.DRAW, friendlyWinner(capped))
        assertNull(whoseTurn(capped))
    }
}
