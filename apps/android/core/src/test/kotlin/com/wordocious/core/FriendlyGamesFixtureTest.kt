    @Test
    fun banner_words_match() {
        val cases = root["banners"]!!.jsonArray
        assertEquals(9, cases.size)
        for (c in cases) {
            val o = c.jsonObject
            val i = o["input"]!!.jsonObject
            val input = FriendsBannerInput(
                friendCount = i["friendCount"]!!.jsonPrimitive.int,
                online = (i["online"] as JsonArray).map { it.jsonPrimitive.content },
                myRank = i["myRank"]!!.jsonPrimitive.int,
                myPoints = i["myPoints"]!!.jsonPrimitive.int,
                leaderName = i["leaderName"]!!.jsonPrimitive.content,
                leaderPoints = i["leaderPoints"]!!.jsonPrimitive.int,
