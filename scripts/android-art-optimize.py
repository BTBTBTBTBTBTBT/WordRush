#!/usr/bin/env python3
"""Android art size policy for res/drawable-nodpi (docs/review/app-size/REPORT.md, "Applied 10-16").

1. No leftover PNGs. Every PNG in drawable-nodpi is converted to lossy WebP (q92, method 6: the same setting
   docs/design/brand/ship-art.py uses for everything but the cast) and the PNG is removed. The resource name is
   unchanged, so R.drawable.* and getIdentifier() keep working. Exception: `bubble_*` is the glyph TINT MAP atlas
   (R/G/B carry data, decoded per pixel by BubbleGlyphTint, byte-identical to web/iOS: build-bubble-atlas.py and
   packages/core/src/bubble-text.test.ts); it must stay a lossless PNG.
2. No byte-identical avatar parts. The avatar maker exports e.g. the pet/brows/extras once per body shape although
   the pixels do not change with the body. Within `art_av_*` the files of an identical group keep ONE file (the
   alphabetically first name) and the others become resource aliases in res/values/art_aliases.xml
   (`<item name="..." type="drawable">@drawable/canonical</item>`), so R.drawable.<name> and getIdentifier("<name>",
   "drawable") still resolve (the app code, the keep rules and the layout are unchanged).

    scripts/android-art-optimize.py           apply (idempotent; re-run after any ship script re-exports the art)
    scripts/android-art-optimize.py --check   exit 1 when a PNG or a duplicate has crept back in (CI guard:
                                              packages/core/src/asset-size-guards.test.ts)

A re-export that re-creates a deleted duplicate file would make aapt2 fail with "duplicate resource"; running this
script (it drops the file again) is the fix.
"""
import glob
import hashlib
import os
import sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
RES = os.path.join(ROOT, 'apps', 'android', 'app', 'src', 'main', 'res')
DRAW = os.path.join(RES, 'drawable-nodpi')
ALIASES = os.path.join(RES, 'values', 'art_aliases.xml')
# 10-16 (2.9 rollback): the 30 PNGs converted to lossy WebP that day are restored to their exact 2.8.4 originals until
# a per-image visual gate exists (iOS lossy broke faint-alpha art); bubble_* is the tint-map atlas (always lossless).
KEEP_PNG_PREFIX = ('bubble_', 'bot_', 'friends_', 'icon3d_', 'mascot_')
DEDUPE_PREFIX = 'art_av_'
WEBP_QUALITY = 92


def md5(p):
    with open(p, 'rb') as f:
        return hashlib.md5(f.read()).hexdigest()


def read_aliases():
    out = {}
    if os.path.exists(ALIASES):
        import re
        for m in re.finditer(r'<item name="([^"]+)" type="drawable">@drawable/([^<]+)</item>', open(ALIASES).read()):
            out[m.group(1)] = m.group(2)
    return out


def pngs():
    return sorted(p for p in glob.glob(os.path.join(DRAW, '*.png')) if not os.path.basename(p).startswith(KEEP_PNG_PREFIX))


def dup_groups():
    by = defaultdict(list)
    for p in glob.glob(os.path.join(DRAW, DEDUPE_PREFIX + '*.webp')):
        by[md5(p)].append(p)
    return [sorted(v) for v in by.values() if len(v) > 1]


def convert(png):
    from PIL import Image
    im = Image.open(png)
    im.load()
    out = png[:-4] + '.webp'
    im.save(out, 'WEBP', quality=WEBP_QUALITY, method=6)
    os.remove(png)
    return out


def write_aliases(aliases):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by scripts/android-art-optimize.py - do not edit. Byte-identical avatar parts keep one file;',
             '     the other names are aliases of it (R.drawable.* and getIdentifier work unchanged). -->',
             '<resources>']
    for name in sorted(aliases):
        lines.append(f'    <item name="{name}" type="drawable">@drawable/{aliases[name]}</item>')
    lines.append('</resources>')
    os.makedirs(os.path.dirname(ALIASES), exist_ok=True)
    with open(ALIASES, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    check = '--check' in sys.argv
    leftovers = pngs()
    groups = dup_groups()
    if check:
        bad = [f'PNG still in drawable-nodpi (convert to WebP): {os.path.basename(p)}' for p in leftovers]
        for g in groups:
            bad.append('byte-identical avatar parts not aliased: ' + ', '.join(os.path.basename(p) for p in g))
        for a, c in read_aliases().items():
            if os.path.exists(os.path.join(DRAW, a + '.webp')):
                bad.append(f'alias {a} shadows a real file (a re-export re-created it)')
            if not os.path.exists(os.path.join(DRAW, c + '.webp')):
                bad.append(f'alias {a} points at missing {c}')
        if bad:
            print(f'{len(bad)} problem(s). Run: python3 scripts/android-art-optimize.py')
            for b in bad[:30]:
                print('  ', b)
            sys.exit(1)
        print('ok: drawable-nodpi has no stray PNGs and no un-aliased duplicate avatar parts')
        return
    converted = [os.path.basename(convert(p)) for p in leftovers]
    aliases = read_aliases()
    removed = 0
    freed = 0
    targets = set(aliases.values())
    for g in dup_groups():
        # keep a file that is already an alias target (stable names), else the alphabetically first
        keep_p = next((p for p in g if os.path.basename(p)[:-5] in targets), g[0])
        keep = os.path.basename(keep_p)[:-5]
        for p in g:
            if p == keep_p:
                continue
            aliases[os.path.basename(p)[:-5]] = keep
            freed += os.path.getsize(p)
            os.remove(p)
            removed += 1
    # An alias must not shadow a real file (a re-export re-created it) and must not dangle (art removed upstream).
    aliases = {a: c for a, c in aliases.items()
               if not os.path.exists(os.path.join(DRAW, a + '.webp')) and os.path.exists(os.path.join(DRAW, c + '.webp'))}
    write_aliases(aliases)
    print(f'converted {len(converted)} PNG -> WebP q{WEBP_QUALITY}; removed {removed} duplicate files ({freed / 1e6:.2f} MB), '
          f'{len(aliases)} aliases in res/values/art_aliases.xml')


if __name__ == '__main__':
    main()
